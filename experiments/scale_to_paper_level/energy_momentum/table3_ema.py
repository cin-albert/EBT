"""Full-set Table 3 protocol (../table3_protocol.py) for T++, S2 and S2 + EMA momentum, on the 33,000 validation
documents and every item of the 4 OOD sets.

Draws follow table3_protocol.score: batch 32 in dataset order, torch.manual_seed(b) per batch, k = 3, σ = 3. The S2
baseline is scored through momentum_mcmc with arm gd_a5, which reproduces the repo's MCMC bit-exactly, so S2 and
S2 + EMA share their random draws (common random numbers).

Usage:
  CUDA_VISIBLE_DEVICES=0 python table3_ema.py score --run ema   # writes results/table3/{run}_{set}.npz
  python table3_ema.py collect                                  # summary.json, report/table3.md, figure
"""
import argparse
import json
import math
from pathlib import Path

import numpy as np
import torch

from table3_protocol import lightning_epoch_ppl, token_ppl

WS = Path(__file__).resolve().parent
OUT = WS / "results/table3"
REPORT = WS / "report"
OOD_SETS = ["gsm8k", "squad", "bigbench_elementary_math_qa", "bigbench_dyck_languages"]
SETS = ["rp_val", *OOD_SETS]
RUNS = {"tpp": ("tpp_paper", None), "s2": ("s2_paper", "gd_a5"), "ema": ("s2_paper", "ema_m0.5")}  # model, arm
N_STEPS, NOISE = 3, 3.0
LOGGED_VAL = {"tpp": 29.75, "s2": 33.94}  # exp(validation CE) logged in training at step 1M (../report/report.md)


def score(model, ds, arm, n_steps: int = N_STEPS, noise: float = NOISE, batch_size: int = 32,
          device: str = "cuda") -> dict[str, np.ndarray]:
    """Per-sequence CE sum and token count over every item of ds, in dataset order; arm None = T++ (one pass)."""
    from harness import batches, token_logprob, tpp_logits
    from momentum import run_momentum_mcmc

    ce_sum, n_tok = [], []
    for b, (inputs, targets, mask) in enumerate(batches(ds, list(range(len(ds))), batch_size)):
        inputs, targets, mask = inputs.to(device), targets.to(device), mask.to(device)
        if arm is None:
            logits = tpp_logits(model, inputs)
        else:
            torch.manual_seed(b)
            logits = run_momentum_mcmc(model, inputs, n_steps, noise, arm)
        nll = -token_logprob(logits, targets).detach() * mask
        ce_sum.append(nll.sum(1).double().cpu().numpy())
        n_tok.append(mask.sum(1).cpu().numpy())
    return {"ce_sum": np.concatenate(ce_sum), "n_tok": np.concatenate(n_tok)}


def ppl_ratio_ci(ce_a: np.ndarray, ce_b: np.ndarray, n_tok: np.ndarray, n: int = 1000,
                 seed: int = 0) -> tuple[float, float, float]:
    """Token-ppl ratio a / b with a paired 95% bootstrap CI over sequences (per-sequence CE sums, shared tokens)."""
    ratio = lambda i: math.exp((ce_a[i].sum() - ce_b[i].sum()) / n_tok[i].sum())
    rng = np.random.default_rng(seed)
    boots = [ratio(rng.integers(0, len(n_tok), len(n_tok))) for _ in range(n)]
    lo, hi = np.percentile(boots, [2.5, 97.5])
    return ratio(np.arange(len(n_tok))), float(lo), float(hi)


def run_score(run: str) -> None:
    from harness import eval_dataset, load_model
    from momentum import ARMS

    model_key, arm = RUNS[run]
    model, hp = load_model(model_key, 1_000_000)
    OUT.mkdir(parents=True, exist_ok=True)
    for s in SETS:
        path = OUT / f"{run}_{s}.npz"
        if path.exists():
            print("skip", path, flush=True)
            continue
        np.savez(path, **score(model, eval_dataset(s, hp), arm and ARMS[arm]))
        print("wrote", path, flush=True)


def summarize() -> dict:
    out = {}
    for run in RUNS:
        for s in SETS:
            r = np.load(OUT / f"{run}_{s}.npz")
            out[f"{run}/{s}"] = {"n_seqs": int(len(r["n_tok"])), "n_tok": int(r["n_tok"].sum()),
                                 "token_ppl": token_ppl(r["ce_sum"], r["n_tok"]),
                                 "epoch_ppl_b8_w4": lightning_epoch_ppl(r["ce_sum"], r["n_tok"], 8, 4)}
    for s in SETS:
        a, b = np.load(OUT / f"ema_{s}.npz"), np.load(OUT / f"s2_{s}.npz")
        assert np.array_equal(a["n_tok"], b["n_tok"]), s
        out[f"ema_vs_s2/{s}"] = dict(zip(("ratio", "lo", "hi"), ppl_ratio_ci(a["ce_sum"], b["ce_sum"], a["n_tok"])))
    return out


def write_table(summ: dict) -> str:
    from collect_paper import PAPER_TABLE3, SET_NAMES

    ppl = lambda run, s: summ[f"{run}/{s}"]["token_ppl"]
    L = ["# Table 3, full-set protocol: paper vs reproduction vs S2 + EMA (generated by table3_ema.py)", "",
         f"Token perplexity exp(mean CE over all tokens) on every item; S2 and S2 + EMA one sample at k = {N_STEPS}, "
         f"σ = {NOISE:g}; validation = all 33,000 validation documents. Paired 95% CI over sequences.", "",
         "| Set | Seqs | T++ paper | EBT paper | T++ ours | S2 ours | S2 + EMA ours | EMA / S2 [95% CI] | "
         "S2 + EMA vs EBT paper | S2 + EMA vs T++ ours |", "|---" * 10 + "|"]
    for i, s in enumerate(SETS):
        c = summ[f"ema_vs_s2/{s}"]
        L.append(f"| {SET_NAMES[s]} | {summ[f'ema/{s}']['n_seqs']:,} | {PAPER_TABLE3['tpp'][i]} | "
                 f"{PAPER_TABLE3['ebt'][i]} | {ppl('tpp', s):.2f} | {ppl('s2', s):.2f} | **{ppl('ema', s):.2f}** | "
                 f"{c['ratio']:.3f} [{c['lo']:.3f}, {c['hi']:.3f}] | {100 * (ppl('ema', s) / PAPER_TABLE3['ebt'][i] - 1):+.1f}% | "
                 f"{100 * (ppl('ema', s) / ppl('tpp', s) - 1):+.1f}% |")
    mean = lambda run: np.mean([ppl(run, s) for s in OOD_SETS])
    L.append(f"| Mean of the 4 OOD sets | | {np.mean(PAPER_TABLE3['tpp'][1:]):.1f} | {np.mean(PAPER_TABLE3['ebt'][1:]):.1f} | "
             f"{mean('tpp'):.2f} | {mean('s2'):.2f} | **{mean('ema'):.2f}** | {mean('ema') / mean('s2'):.3f} | "
             f"{100 * (mean('ema') / np.mean(PAPER_TABLE3['ebt'][1:]) - 1):+.1f}% | {100 * (mean('ema') / mean('tpp') - 1):+.1f}% |")
    L += ["", "Lightning epoch aggregation (batch 8, 4 GPUs; table3_protocol.lightning_epoch_ppl), same runs:", "",
          "| Set | T++ ours | S2 ours | S2 + EMA ours |", "|---|---|---|---|"]
    L += [f"| {SET_NAMES[s]} | " + " | ".join(f"{summ[f'{r}/{s}']['epoch_ppl_b8_w4']:.2f}" for r in RUNS) + " |"
          for s in SETS]
    L += ["", f"Validation as logged in training (33,000 documents, repo validation loop): T++ {LOGGED_VAL['tpp']}, "
          f"S2 {LOGGED_VAL['s2']}."]
    return "\n".join(L) + "\n"


def plot(summ: dict, path: Path) -> None:
    """../collect_paper.plot_vs_paper with a third panel: paper's EBT (hollow) -> our S2 + EMA (filled)."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.lines import Line2D
    from matplotlib.ticker import FixedLocator, NullLocator, ScalarFormatter

    from collect_paper import PAPER_TABLE3, SET_COLORS, SET_NAMES, style

    panels = [("tpp", "tpp", "Transformer++"), ("ebt", "s2", "EBT (System 2)"),
              ("ebt", "ema", "EBT + EMA momentum (μ = 0.5)")]
    fig, axes = plt.subplots(1, 3, figsize=(13, 4.8), sharey=True)
    for ax, (paper, run, title) in zip(axes, panels):
        for i, (s, c) in enumerate(zip(SETS, SET_COLORS)):
            p, o = PAPER_TABLE3[paper][i], summ[f"{run}/{s}"]["token_ppl"]
            ax.plot([0, 1], [p, o], color=c, lw=2, zorder=2)
            ax.plot(0, p, "o", ms=8, mfc="white", mec=c, mew=2, zorder=3)
            ax.plot(1, o, "o", ms=8, color=c, mec="white", mew=1.5, zorder=3)
            ax.annotate(f"{SET_NAMES[s]}  {100 * (o / p - 1):+.0f}%", (1, o), xytext=(10, 0),
                        textcoords="offset points", va="center", fontsize=8, color="#0b0b0b")
        ax.set_yscale("log")
        ax.yaxis.set_major_locator(FixedLocator([30, 40, 50, 70, 100, 140]))
        ax.yaxis.set_major_formatter(ScalarFormatter())
        ax.yaxis.set_minor_locator(NullLocator())
        ax.set_xticks([0, 1], ["Paper (Table 3)" if paper == "tpp" else "Paper EBT (Table 3)", "Ours"])
        ax.set_xlim(-0.25, 1.85)
        style(ax, "", "Perplexity (log scale)" if run == "tpp" else "", title)
        ax.grid(axis="x", visible=False)
    handles = [Line2D([], [], color=c, lw=2, marker="o", ms=6, label=SET_NAMES[s]) for s, c in zip(SETS, SET_COLORS)]
    fig.legend(handles=handles, loc="upper center", ncol=5, frameon=False, fontsize=8, bbox_to_anchor=(0.5, 0.94))
    fig.suptitle("Table 3 perplexity, full-set protocol: paper vs reproduction vs S2 + EMA "
                 f"(xxs, 128M sequences; k = {N_STEPS}, σ = {NOISE:g}; label = ours vs paper)", fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.9))
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=160)
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("score").add_argument("--run", choices=sorted(RUNS), required=True)
    sub.add_parser("collect")
    args = ap.parse_args()
    if args.cmd == "score":
        run_score(args.run)
        return
    summ = summarize()
    (OUT / "summary.json").write_text(json.dumps(summ, indent=1))
    (REPORT / "table3.md").write_text(write_table(summ))
    plot(summ, REPORT / "figures/table3_vs_paper_ema.png")
    print((REPORT / "table3.md").read_text())


if __name__ == "__main__":
    main()
