"""Pre-registered claims D1-D5 (IMPLEMENTATION_PLAN.md §0.3) -> report/result.md and report/figures/*.png.

Inputs: run_decay.py outputs in results/single/<arm>_<set>/, and the momentum grid's gd_a5, gd_a7.5 and ema_m0.5
in ../energy_momentum/results/single/ (same sequences and seeds, so every comparison is paired).
Usage: python collect_decay.py
"""
import math
from pathlib import Path

import numpy as np

from collect_momentum import (C_ARM, C_EBT, C_EXTRA, C_TPP, K_LIST, MUTED, NOISES, OOD_SETS, SET_NAMES, SETS,
                              ce_after_k, mean_ood_ppl, paired_bootstrap, pct_ppl, tpp_ce, verdict_m1)
from decay_arms import DECAY_ARMS
from momentum import ARMS, step_size

WS = Path(__file__).resolve().parent
RES = WS / "results/single"
RES_MOMENTUM = WS.parent / "energy_momentum/results/single"
REPORT = WS / "report"
REFS = ["gd_a5", "gd_a7.5", "ema_m0.5"]
EXPLAINS_MOST, MOMENTUM_DOES_MORE = 73.2, 78.0  # §0.3: ema_m0.5 72.21 + 1; best GD with alpha >= 5 over all k
DRIFT_MAX, CYCLE_MAX = 0.02, 0.05


def select_d_star(rp_val_ce_k3: dict[str, float]) -> str:
    """Lowest rp_val CE at k = 3 among the GD step-size arms (the EMA combination is not a candidate)."""
    return min((a for a in rp_val_ce_k3 if not a.startswith("ema_")), key=rp_val_ce_k3.get)


def verdict_d1(ppl: float) -> str:
    if ppl <= EXPLAINS_MOST:
        return "step size explains most"
    return "momentum does more" if ppl >= MOMENTUM_DOES_MORE else "partial"


def drift(ppl_k3: float, ppl_k32: float) -> float:
    return ppl_k32 / ppl_k3 - 1


# ---------------------------------------------------------------- loading
def load(arm: str, data: str, noise: float) -> dict:
    root = RES if arm in DECAY_ARMS else RES_MOMENTUM
    return dict(np.load(root / f"{arm}_{data}" / f"part_a_noise{noise:g}.npz"))


def summarize(arms: list[str]) -> dict:
    """ce[arm][set][noise][k] = mean CE over tokens."""
    return {arm: {s: {nz: {k: float(ce_after_k(a, k).mean()) for k in K_LIST} for nz in NOISES
                      for a in [load(arm, s, nz)]} for s in SETS} for arm in arms}


def ood_ppl(ce: dict, arm: str, k: int, noise: float = 3.0) -> float:
    return mean_ood_ppl({s: ce[arm][s][noise][k] for s in OOD_SETS})


def paired(arm_a: str, arm_b: str, data: str, k: int = 3, noise: float = 3.0) -> tuple[float, float, float]:
    a, b = load(arm_a, data, noise), load(arm_b, data, noise)
    assert np.array_equal(a["seq_id"], b["seq_id"]), (arm_a, arm_b, data)
    return paired_bootstrap(ce_after_k(a, k), ce_after_k(b, k), a["seq_id"])


def two_cycle(arm: str) -> float:
    from analyze_q3_extra import cycle_metrics
    return cycle_metrics(load(arm, "rp_val", 0.0))["share_two_cycle"]


# ---------------------------------------------------------------- claims and report
def claims(ce: dict, d_star: str) -> list[dict]:
    rows = []
    d3 = ood_ppl(ce, d_star, 3)
    rows.append({"id": "D1", "value": f"{d_star}: {d3:.2f} (ema_m0.5 {ood_ppl(ce, 'ema_m0.5', 3):.2f}, "
                 f"gd_a5 {ood_ppl(ce, 'gd_a5', 3):.2f})",
                 "rule": f"≤ {EXPLAINS_MOST} most / ≥ {MOMENTUM_DOES_MORE} momentum does more",
                 "verdict": verdict_d1(d3)})
    pct = pct_ppl(ood_ppl(ce, "gd_a5", 3), d3)
    his = [paired(d_star, "gd_a5", s)[2] for s in OOD_SETS]
    rows.append({"id": "D2", "value": f"{pct:+.1f}%, CI < 0 on {sum(h < 0 for h in his)}/4",
                 "rule": "> 2% and CI < 0 on ≥ 3/4", "verdict": supported(verdict_m1(pct, his))})
    cyc = two_cycle(d_star)
    rows.append({"id": "D3", "value": f"{100 * cyc:.1f}% (gd_a5 {100 * two_cycle('gd_a5'):.1f}%)",
                 "rule": f"< {100 * CYCLE_MAX:g}%", "verdict": supported(cyc < CYCLE_MAX)})
    dr = drift(d3, ood_ppl(ce, d_star, 32))
    rows.append({"id": "D4", "value": f"{100 * dr:+.1f}% (ema_m0.5 "
                 f"{100 * drift(ood_ppl(ce, 'ema_m0.5', 3), ood_ppl(ce, 'ema_m0.5', 32)):+.1f}%)",
                 "rule": f"< +{100 * DRIFT_MAX:g}%", "verdict": supported(dr < DRIFT_MAX)})
    his5 = [paired("ema_m0.5_harm", "ema_m0.5", s)[2] for s in OOD_SETS]
    rows.append({"id": "D5 (exploratory)", "value": f"{ood_ppl(ce, 'ema_m0.5_harm', 3):.2f} vs "
                 f"{ood_ppl(ce, 'ema_m0.5', 3):.2f}, CI < 0 on {sum(h < 0 for h in his5)}/4",
                 "rule": "CI < 0 on ≥ 3/4", "verdict": supported(sum(h < 0 for h in his5) >= 3)})
    return rows


def supported(ok: bool) -> str:
    return "**Supported**" if ok else "**Not supported**"


def write_result(ce: dict, arms: list[str], d_star: str, rows: list[dict]) -> str:
    tpp = tpp_ce()
    L = ["# Step-size decay results (generated by collect_decay.py)", "",
         f"Selected on rp_val at k = 3, σ = 3: **d\\* = {d_star}**.", "",
         "## Pre-registered claims", "", "| # | Value | Supported if | Verdict |", "|---|---|---|---|"]
    L += [f"| {r['id']} | {r['value']} | {r['rule']} | {r['verdict']} |" for r in rows]

    cols = list(dict.fromkeys(["gd_a5", "ema_m0.5", d_star, "ema_m0.5_harm"]))
    L += ["", "## Per-set perplexity at k = 3 (σ = 3)", "",
          "| Set | T++ ours | " + " | ".join(cols) + f" | {d_star} vs gd_a5: ΔCE [95% CI] | "
          f"{d_star} vs ema_m0.5: ΔCE [95% CI] |", "|---" * (len(cols) + 4) + "|"]
    for s in SETS:
        cis = [paired(d_star, ref, s) for ref in ("gd_a5", "ema_m0.5")]
        L.append(f"| {SET_NAMES[s]} | {math.exp(tpp[s]):.2f} | "
                 + " | ".join(f"{math.exp(ce[a][s][3.0][3]):.2f}" for a in cols) + " | "
                 + " | ".join(f"{m:+.3f} [{lo:+.3f}, {hi:+.3f}]" for m, lo, hi in cis) + " |")
    L.append("| Mean of 4 OOD sets | " + f"{mean_ood_ppl({s: tpp[s] for s in OOD_SETS}):.2f} | "
             + " | ".join(f"{ood_ppl(ce, a, 3):.2f}" for a in cols) + " | | |")

    for noise in NOISES:
        L += ["", f"## Mean OOD ppl vs k (σ = {noise:g})", "",
              "| Arm | α₀, α₁, α₂ | " + " | ".join(f"k={k}" for k in K_LIST) + " |", "|---" * (len(K_LIST) + 2) + "|"]
        for a in arms:
            arm = DECAY_ARMS.get(a) or ARMS[a]
            alphas = ", ".join(f"{step_size(arm, t):.3g}" for t in range(3))
            L.append(f"| {a} | {alphas} | " + " | ".join(f"{ood_ppl(ce, a, k, noise):.1f}" for k in K_LIST) + " |")

    L += ["", "## rp_val CE at k = 3 (σ = 3), used for selection", "", "| Arm | CE |", "|---|---|"]
    L += [f"| {a} | {ce[a]['rp_val'][3.0][3]:.4f} |" for a in arms]
    L += ["", "## 2-cycles (rp_val, σ = 0, t = 31)", "", "| Arm | share two-cycle |", "|---|---|"]
    L += [f"| {a} | {100 * two_cycle(a):.1f}% |" for a in arms]
    return "\n".join(L) + "\n"


def plot(ce: dict, arms: list[str], d_star: str, path: Path) -> None:
    """α_t per arm, and mean OOD ppl vs k at σ = 3 and σ = 0; d*, gd_a5, ema_m0.5 highlighted, others muted."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    tpp_mean = mean_ood_ppl({s: tpp_ce()[s] for s in OOD_SETS})
    key = {"gd_a5": ("gd_a5 (trained α)", C_EBT, "-"), "ema_m0.5": ("ema_m0.5 (momentum)", C_ARM, "-"),
           d_star: (f"{d_star} (d*)", C_EXTRA, "-"), "ema_m0.5_harm": ("ema_m0.5_harm", C_ARM, (0, (4, 2)))}
    ks = [k for k in K_LIST if k > 1]
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.2), gridspec_kw={"width_ratios": [0.8, 1, 1]})
    t = np.arange(10)
    for a in arms:
        arm = DECAY_ARMS.get(a) or ARMS[a]
        label, color, ls = key.get(a, (None, MUTED, "-"))
        axes[0].plot(t, [step_size(arm, i) for i in t], ls=ls, color=color, lw=2 if a in key else 1,
                     alpha=1 if a in key else 0.5, marker="o", ms=3, label=label)
    axes[0].set(xlabel="update t", ylabel="step size α_t", title="Schedules (gray: other arms)")
    for ax, noise in zip(axes[1:], (3.0, 0.0)):
        for a in [a for a in arms if a not in key] + [a for a in key if a in arms]:
            label, color, ls = key.get(a, (None, MUTED, "-"))
            ax.plot(ks, [ood_ppl(ce, a, k, noise) for k in ks], ls=ls, color=color, lw=2 if a in key else 1,
                    alpha=1 if a in key else 0.5, marker="o", ms=3 if a in key else 2, label=label)
        ax.axhline(tpp_mean, color=C_TPP, ls=":", lw=2, label="Transformer++ (1 pass)")
        ax.axvline(3, color=MUTED, lw=1, alpha=0.4)
        ax.set_xscale("log", base=2)
        ax.set_xticks(ks, [str(k) for k in ks], fontsize=8)
        ax.set_ylim(60, 130)
        ax.set(xlabel="MCMC steps k (trained: 3)", ylabel="mean OOD perplexity (4 sets)", title=f"σ = {noise:g}")
    axes[1].legend(frameon=False, fontsize=8, loc="upper right", handlelength=3)
    for ax in axes:
        ax.grid(alpha=0.2)
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main() -> None:
    arms = [*REFS, *DECAY_ARMS]
    ce = summarize(arms)
    d_star = select_d_star({a: ce[a]["rp_val"][3.0][3] for a in DECAY_ARMS})
    rows = claims(ce, d_star)
    (REPORT / "figures").mkdir(parents=True, exist_ok=True)
    (REPORT / "result.md").write_text(write_result(ce, arms, d_star, rows))
    plot(ce, arms, d_star, REPORT / "figures/ce_vs_k.png")
    print((REPORT / "result.md").read_text())


if __name__ == "__main__":
    main()
